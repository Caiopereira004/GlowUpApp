class ProductModel {
  final String id;
  final String name;
  final String category;
  final String skinTag;
  final String store;
  final String url;
  final double price;
  final String temp;

  const ProductModel({
    required this.id,
    required this.name,
    required this.category,
    required this.skinTag,
    required this.store,
    required this.url,
    required this.price,
    required this.temp,
  });
}
